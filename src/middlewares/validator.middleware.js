import {validationResult} from "express-validator"
import {ApiError} from "../utils/api-error.js"

// validationResult(req) automatically retrieves validation like we do not have to pass them in this validators folder index.js is there
//that will do all validations and all those errors are automatically stored in that validationResult once we call for that specific validate request we get
//then itll retrive the results for that request and then if empty itll go to next if not itll extract those errors but they are like not perfect format
//so what we do is we extract those errors neatly this err.path is the err.param like what parameter is wrong err.msg is what msg we kept like those in validators index.js
// errors generated by express-validator middleware from req

export const validate=(req,res,next)=>{
    const errors=validationResult(req)

    if(errors.isEmpty())
    {
        return next()
    }

    const extractedErrors=[]

    errors.array().map((err)=>
        extractedErrors.push({[err.path]:err.msg})
    )

    //[
//   { email: "Invalid email" },
//   { password: "Password too short" }
// ]

    throw new ApiError(
        422,
        "Received Data is not valid",
        extractedErrors
    )
}